const ALL_TRANSLATIONS: Record<LangCode, Translations> = {
  en, hi, ta, te, mr, bn, kn, gu, ml, as: as_lang,
};

// Interpolation-friendly t() helper — supports {placeholder} style keys.
export function t(key: string, lang: LangCode = 'en', vars?: Record<string, string | number>): string {
  const raw = ALL_TRANSLATIONS[lang]?.[key] || ALL_TRANSLATIONS.en[key] || key;
  if (!vars) return raw;
  return Object.entries(vars).reduce<string>(
    (acc, [k, v]) => acc.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v)),
    raw
  );
}

